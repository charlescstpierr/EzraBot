import assert from 'node:assert/strict';
import {mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openStore} from '../dist/src/store.js';
import {loadMascots} from '../dist/src/domain.js';
import {minoServer} from './lib/isolated-mino.mjs';
import {backgroundFixture} from './lib/background-fixture.mjs';
import {browser,until} from './lib/browser.mjs';
import {buildFingerprint} from './lib/build-fingerprint.mjs';

const root=new URL('../',import.meta.url);
const codeSnapshot=buildFingerprint(root);
const dir=mkdtempSync(join(tmpdir(),'mino-audit-ui-'));
const store=openStore({path:join(dir,'mino.sqlite'),mascots:loadMascots(new URL('assets/mascots.json',root))});
const dispatch=command=>{const r=store.dispatch({requestId:crypto.randomUUID(),...command});assert(r.ok,r.message);return r.result;};
const claim=()=>{const c=store.claimNext('doc');assert(c);return c;};
const result=body=>({kind:'succeeded',reply:{reply:body===null?'AVIS_ENREGISTRE':'BROUILLON_ENREGISTRE',deliverable:body===null?null:{title:'Note',body}},used:{model:'controlled-audit',effort:'low',speed:'standard'},threadId:'audit',turnId:crypto.randomUUID()});
const goals=dispatch({type:'message.send',botId:'mino',text:'Prépare une note sur mon objectif',attachments:[],document:{reviewerBotId:null}});
for(const text of ['OBJECTIF_REMPLACE_728','OBJECTIF_ACTUEL_936'])dispatch({type:'task.intent',taskId:goals.taskId,intent:{kind:'change_goal',text}});
const g=claim();store.bindThread(g,'goals-thread');store.bindTurn(g,'goals-turn');store.finishJob(g,result('DOCUMENT_OBJECTIF_ACTUEL'));
const stopped=dispatch({type:'message.send',botId:'mino',text:'Prépare une note à relire',attachments:[],document:{reviewerBotId:'pixel'}});
store.finishJob(claim(),result('DOCUMENT_CONFIRME_AVANT_INTERRUPTION'));
store.finishJob(claim(),result(null));claim();store.close();
let server,b;
try{
  server=await minoServer({root,dataDir:dir,port:4390,codexBin:backgroundFixture(dir)});
  b=await browser(join(dir,'chrome'));await b.navigate(server.base);
  const shown=expression=>until(()=>b.evaluate(expression),Boolean,'état d’interface attendu');
  const click=selector=>b.click(`document.querySelector(${JSON.stringify(selector)})`);
  await shown(`document.querySelector('.task-card[data-task-id="${goals.taskId}"] .task-open')`);
  await click(`.task-card[data-task-id="${goals.taskId}"] .task-open`);
  await shown(`document.querySelector('.doc-intent[data-delivery="superseded"]')`);
  assert(await b.evaluate(`document.querySelector('.doc-intent[data-delivery="superseded"]').textContent.includes('Aucun tour accepté')`));
  assert.equal(await b.evaluate(`document.querySelectorAll('.doc-intent[data-delivery="sent"]').length`),1);
  await click('.doc-close');await click(`.task-card[data-task-id="${stopped.taskId}"] .task-open`);
  await shown(`document.querySelector('#doc-panel').dataset.status==='stopped'&&document.querySelector('.doc-propose')`);
  assert.equal(await b.evaluate(`document.querySelector('.doc-editor-body').value`),'DOCUMENT_CONFIRME_AVANT_INTERRUPTION');
  await b.fill('.doc-editor-body','CORRECTION_HUMAINE_APRES_INTERRUPTION');await click('.doc-save');
  await shown(`document.querySelector('.doc-save').disabled&&document.querySelector('.doc-propose')&&!document.querySelector('.doc-propose').disabled`);
  await click('.doc-propose');await shown(`document.querySelector('.doc-approve')`);await click('.doc-approve');
  const view=await until(server.view,v=>v.carnet.some(p=>p.body==='CORRECTION_HUMAINE_APRES_INTERRUPTION'),'copie locale exacte');
  const task=view.tasks.find(t=>t.id===stopped.taskId);assert(task);
  assert.equal(task.calls.length,3);assert.equal(task.calls.at(-1).state,'interrupted');
  assert.equal(view.messages.filter(m=>m.role==='assistant'&&m.threadBotId==='mino').length,3);
  await b.rpc('Emulation.setDeviceMetricsOverride',{width:390,height:844,deviceScaleFactor:1,mobile:true});
  await shown(`getComputedStyle(document.querySelector('.doc-back')).display!=='none'`);
  assert.equal(await b.evaluate('document.documentElement.scrollWidth>innerWidth'),false);
  const proof={passed:true,checkedAt:new Date().toISOString(),codeSnapshot,scope:'Isolated Chrome and temporary SQLite. Results seeded with controlled events; no model call.',checks:['superseded goal is never labelled transmitted','latest goal retains its actual receipt','interrupted synthesis keeps the confirmed document editable','exact edited version can be approved and published','confirmed replies and interrupted attempt stay recorded','no additional model call is started','mobile document has no horizontal page overflow']};
  writeFileSync(new URL('docs/evidence/audit-ui.json',root),JSON.stringify(proof,null,2)+'\n');console.log(JSON.stringify({passed:true,checks:proof.checks.length}));
}finally{if(b)await b.close();if(server)await server.stop();}
