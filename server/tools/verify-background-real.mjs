import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {mkdtempSync,writeFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {openStore} from '../dist/src/store.js';
import {loadMascots} from '../dist/src/domain.js';
import {DiagnosticsSchema} from '../dist/src/protocol.js';
import {minoServer} from './lib/isolated-mino.mjs';
import {until,delay} from './lib/browser.mjs';
import {buildFingerprint} from './lib/build-fingerprint.mjs';

assert(!process.env.MINO_CODEX_BIN,'Cette vérification exige le moteur officiel.');
const root=new URL('../',import.meta.url);
const codeSnapshot=buildFingerprint(root);
const sourceCommit=execFileSync('git',['rev-parse','HEAD'],{cwd:root,encoding:'utf8'}).trim();
const dir=mkdtempSync(join(tmpdir(),'mino-background-real-'));
const port=Number(process.env.MINO_BACKGROUND_REAL_PORT??4392);
const evidenceName=process.env.MINO_BACKGROUND_REAL_EVIDENCE??'background-real.json';
assert(/^[a-z0-9-]+\.json$/.test(evidenceName),'Le nom de preuve doit être un fichier JSON dans docs/evidence.');
const evidence=new URL('docs/evidence/'+evidenceName,root);
const reviewerToken='REVIEW_CHECK_'+randomUUID().replaceAll('-','').slice(0,12);
const chatToken='CHAT_CHECK_'+randomUUID().replaceAll('-','').slice(0,12);
const store=openStore({path:join(dir,'mino.sqlite'),mascots:loadMascots(new URL('assets/mascots.json',root))});
const configured=store.dispatch({type:'bot.update',requestId:randomUUID(),botId:'nova',instructions:`Pour ce test synthétique de revue documentaire, donne un avis bref et deux améliorations concrètes. Termine ton avis par le code exact ${reviewerToken}. Ce code doit être transmis au rédacteur dans ton avis. Aucune recherche ni outil.`});
assert(configured.ok);store.close();
let server;
let phase='startup';
const startedAt=new Date().toISOString();
const write=proof=>writeFileSync(evidence,JSON.stringify(proof,null,2)+'\n');
write({passed:false,startedAt,phase,codeSnapshot,sourceCommit});
const accepted=async command=>{const r=await server.post(command);assert(r.ok,r.message);return r.result;};
try{
  server=await minoServer({root,dataDir:dir,port});
  phase='document_started';
  const sent=await accepted({type:'message.send',botId:'mino',text:'Prépare un document concret en français pour organiser un jardin partagé fictif. Environ 900 mots, huit sections, responsabilités, calendrier et critères de réussite. Sans recherche externe ni action réelle. Produis le document complet dans le livrable. Après la revue du second bot, incorpore ses améliorations et conserve tout code de contrôle qu’il demande explicitement de faire figurer dans le document final. Réponds brièvement dans le chat.',attachments:[],document:{reviewerBotId:'nova'}});
  const firstView=await server.view();const task=firstView.tasks.find(t=>t.requestMessageId===sent.messageId);assert(task);
  const getTask=async()=>(await server.view()).tasks.find(t=>t.id===task.id);
  const prefixes=new Set();
  const progressAt=[];
  const writing=await until(getTask,t=>{
    if(t?.progress?.step==='draft'&&t.progress.body?.length>20){prefixes.add(t.progress.body);progressAt.push({at:Date.now(),chars:t.progress.body.length});}
    return prefixes.size>=2&&t.calls.some(c=>c.state==='running'&&c.step==='draft');
  },'deux états documentaires reçus du vrai moteur',180000);
  const firstProgressAt=progressAt[0].at;
  phase='concurrent_chat';
  const chatStartedAt=Date.now();
  const chat=await accepted({type:'message.send',botId:'mino',text:`Réponds uniquement ${chatToken}, sans livrable.`,attachments:[]});
  const chatView=await until(server.view,v=>v.works.find(w=>w.id===chat.workId)?.state==='done','réponse réelle du chat',120000);
  const chatCompletedAt=Date.now();
  assert(chatView.messages.some(m=>m.workId===chat.workId&&m.role==='assistant'&&m.text.includes(chatToken)));
  assert(chatView.tasks.find(t=>t.id===task.id).calls.some(c=>c.state==='running'),'Le chat doit terminer pendant une vraie exécution documentaire.');
  phase='relay';
  const finished=await until(getTask,t=>t?.status==='finished'&&t.calls.length===3,'relais documentaire complet',240000);
  const before=await server.view();const author=before.works.find(w=>w.id===task.authorWorkId);assert(author);
  assert.deepEqual(finished.calls.map(c=>c.step),['draft','review','synthesis']);
  assert.deepEqual(finished.calls.map(c=>c.botId),['mino','nova','mino']);
  assert(finished.calls.every(c=>c.state==='succeeded'&&c.turnAccepted));
  assert.equal(finished.maxCalls,3);
  const draft=author.versions[0];const final=author.versions.at(-1);assert(draft?.body.length>2000);assert(final);
  for(const prefix of prefixes)assert(draft.body.startsWith(prefix),'Un fragment reçu doit appartenir au brouillon effectivement livré.');
  const review=before.messages.find(m=>m.role==='assistant'&&m.workId===finished.reviewWorkId);assert(review?.text.includes(reviewerToken));
  assert(final.body.includes(reviewerToken),'La synthèse doit intégrer le code inconnu du rédacteur avant la revue.');
  assert(finished.handoffs.some(h=>h.fromStep==='draft'&&h.readBy.some(r=>r.botId==='nova'&&r.step==='review')));
  assert(finished.handoffs.some(h=>h.fromStep==='review'&&h.readBy.some(r=>r.botId==='mino'&&r.step==='synthesis')));
  await delay(200);
  const metadata=DiagnosticsSchema.parse(await server.diagnostics());
  const ids=new Set([...finished.calls.map(c=>c.workId),chat.workId]);
  const attempts=metadata.attempts.filter(a=>ids.has(a.workId));assert.equal(attempts.length,4);
  assert(attempts.every(a=>a.used?.model&&a.threadId&&a.turnId));
  assert(!JSON.stringify(metadata).includes(reviewerToken),'Les diagnostics restent sans contenu.');
  const stable=JSON.stringify({versions:author.versions,handoffs:finished.handoffs,messages:before.messages});
  phase='restart';
  await server.stop();server=null;
  server=await minoServer({root,dataDir:dir,port});
  const after=await server.view();const restored=after.tasks.find(t=>t.id===task.id);assert(restored);
  assert.equal(restored.status,'finished');assert.equal(restored.calls.length,3);
  assert.equal(JSON.stringify({versions:after.works.find(w=>w.id===task.authorWorkId).versions,handoffs:restored.handoffs,messages:after.messages}),stable);
  await delay(500);assert.equal((await getTask()).calls.length,3,'Aucun appel supplémentaire au redémarrage.');
  phase='interrupted_real_call';
  const interruption=await accepted({type:'message.send',botId:'mino',text:'Rédige un document fictif de 1000 mots sur les activités mensuelles d’un jardin collectif. Douze sections concrètes. Écris le document entier dans le livrable. Aucun outil ni recherche. Toute précision reçue à une prochaine passe doit figurer dans son document.',attachments:[],document:{reviewerBotId:null}});
  const interruptedId=(await server.view()).tasks.find(t=>t.requestMessageId===interruption.messageId)?.id;assert(interruptedId);
  const getInterrupted=async()=>(await server.view()).tasks.find(t=>t.id===interruptedId);
  const partial=await until(getInterrupted,t=>t?.progress?.body?.length>40&&t.calls.some(c=>c.state==='running'),'fragment réel avant interruption',180000);
  const infoToken='AFTER_RESTART_'+randomUUID().replaceAll('-','').slice(0,12);
  await accepted({type:'task.intent',taskId:interruptedId,intent:{kind:'add_info',text:`Inclure exactement le code ${infoToken} dans le document final.`}});
  assert.equal((await getInterrupted()).events.at(-1).delivery.state,'waiting');
  await server.stop('SIGKILL');server=null;
  server=await minoServer({root,dataDir:dir,port});
  const recovered=await getInterrupted();assert.equal(recovered.status,'stopped');assert.equal(recovered.calls.length,1);
  assert(recovered.progress.body.startsWith(partial.progress.body));
  assert.equal(recovered.events.at(-1).delivery.state,'waiting');
  await delay(500);assert.equal((await getInterrupted()).calls.length,1);
  phase='manual_real_resume';
  await accepted({type:'task.continue',taskId:interruptedId});
  const resumed=await until(getInterrupted,t=>t?.status==='finished'&&t.calls.length===2,'reprise réelle explicite',240000);
  const last=await server.view();const resumedDocument=last.works.find(w=>w.id===resumed.authorWorkId)?.versions.at(-1);assert(resumedDocument?.body.includes(infoToken));
  assert.equal(resumed.events.at(-1).delivery.state,'sent');
  await delay(200);
  const finalMetadata=DiagnosticsSchema.parse(await server.diagnostics());
  ids.add(resumed.authorWorkId);
  const allAttempts=finalMetadata.attempts.filter(a=>ids.has(a.workId));assert.equal(allAttempts.length,6);
  assert(!JSON.stringify(finalMetadata).includes(infoToken));
  const proof={passed:true,startedAt,codeSnapshot,checkedAt:new Date().toISOString(),sourceCommit,scope:'Production HTTP server, worker, SQLite and two official Codex App Server connections. Synthetic content only. Six actual model calls including one interrupted call. No external action.',checks:{progressiveDocument:true,persistedDraftMatchesReceivedPrefixes:true,chatCompletesDuringDocument:true,authorReviewerAuthor:true,reviewUsedInSynthesis:true,threeCallBudget:true,immutableVersionsSurviveRestart:true,noAutomaticRerun:true,partialSurvivesRealCrash:true,manualResumeConsumesPendingInformation:true,metadataOnly:true},document:{taskId:task.id,progressSnapshots:prefixes.size,firstProgressAt,draftChars:draft.body.length,finalChars:final.body.length,versions:author.versions.length},chat:{chatStartedAt,chatCompletedAt},interruption:{taskId:interruptedId,retainedChars:recovered.progress.body.length,calls:resumed.calls.length},attempts:allAttempts,note:'A peer review proves a transmission path, not independent factual correctness. Conflict and cancellation cases use separately labelled controlled fixtures. Token usage is only reported when supplied by the provider.'};
  write(proof);console.log(JSON.stringify({passed:true,evidence:evidence.pathname,calls:allAttempts.length,steps:finished.calls.map(c=>c.step)}));
}catch(error){write({passed:false,startedAt,codeSnapshot,sourceCommit,checkedAt:new Date().toISOString(),phase,note:'Parcours réel incomplet. Aucun résultat simulé ne remplace cet échec.'});throw error;}
finally{if(server)await server.stop();}
